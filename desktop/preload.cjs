const { contextBridge, ipcRenderer } = require('electron')
contextBridge.exposeInMainWorld('desktop', Object.freeze({
  recover: operation => ipcRenderer.invoke(`recovery:${operation}`),
  presence: account => ipcRenderer.invoke('desktop:presence', account),
  deleteSecret: account => ipcRenderer.invoke('desktop:delete', account),
  test: () => ipcRenderer.invoke('desktop:test'),
  pause: paused => ipcRenderer.invoke('desktop:pause', paused),
  agents: () => ipcRenderer.invoke('desktop:agents'),
  agentCreate: (name, max, daily) => ipcRenderer.invoke('desktop:agent-create', name, max, daily),
  agentControl: (id, operation) => ipcRenderer.invoke('desktop:agent-control', id, operation),
  agentCopy: id => ipcRenderer.invoke('desktop:agent-copy', id),
  promptBudget: input => ipcRenderer.invoke('desktop:prompt-budget', input),
  receipts: id => ipcRenderer.invoke('desktop:receipts', id),
  exportData: () => ipcRenderer.invoke('desktop:export'),
  reset: confirmation => ipcRenderer.invoke('desktop:reset', confirmation),
  updates: () => ipcRenderer.invoke('desktop:updates'),
  state: () => ipcRenderer.invoke('desktop:state'),
  save: input => ipcRenderer.invoke('desktop:save', input),
  secret: (account, value) => ipcRenderer.invoke('desktop:secret', account, value),
  wallets: () => ipcRenderer.invoke('desktop:wallets'),
  mcp: () => ipcRenderer.invoke('desktop:mcp'),
}))
