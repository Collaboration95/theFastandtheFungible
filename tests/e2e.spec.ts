test('plan review edits permitted fields and gates execution behind approval', async ({ page }) => {
  await continueCanonicalSetup(page)
  await expect(page.getByRole('heading', { name: '12 previews from approved fixture profiles' })).toHaveCount(0)
  await page.getByRole('radio', { name: /Thesis stress test/i }).check()
  await page.getByText('Advanced plan fields and stop conditions', { exact: true }).click()
  await page.getByLabel('Plan research question').fill('What could invalidate the 2028 capacity thesis?')
  await page.getByLabel('Plan decision').fill('Decide whether to delay the buildout commitment.')
  await page.getByLabel('Plan research horizon').fill('Through 2030')
  await page.getByLabel('Plan step 1 objective').fill('Frame a falsification test before reading sources.')
  await page.getByLabel('Stop condition 1 label').fill('No usable baseline remains')
  await page.getByLabel('Stop condition 1 rule').fill('Stop when the approved profiles contain no readable baseline evidence.')
  await page.getByRole('button', { name: 'Save draft' }).click()
  await expect(page.getByRole('contentinfo').getByText('Draft saved locally. No research, purchase, or charge occurred.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Review the research plan' })).toBeVisible()
  await expect(page.getByLabel('Plan research question')).toHaveValue('What could invalidate the 2028 capacity thesis?')
  await expect(page.getByLabel('Plan decision')).toHaveValue('Decide whether to delay the buildout commitment.')
  await expect(page.getByLabel('Plan research horizon')).toHaveValue('Through 2030')
  await expect(page.getByLabel('Plan step 1 objective')).toHaveValue('Frame a falsification test before reading sources.')
  await expect(page.getByLabel('Stop condition 1 label')).toHaveValue('No usable baseline remains')
  await expect(page.getByLabel('Stop condition 1 rule')).toHaveValue('Stop when the approved profiles contain no readable baseline evidence.')
  await page.getByRole('button', { name: 'Approve plan & start research' }).click()
  await page.getByRole('tab', { name: /Sources/ }).click()
  await expect(page.getByRole('heading', { name: '12 previews from approved fixture profiles' })).toBeVisible()
})
