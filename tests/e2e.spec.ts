test('canonical fixture run makes the budget decisions visible', async ({ page }) => {
  await continueCanonicalSetup(page)
  await page.getByRole('button', { name: 'Approve plan & start research' }).click()
  await page.getByRole('tab', { name: /Sources/ }).click()
  await expect(page.getByRole('heading', { name: '12 previews from approved fixture profiles' })).toBeVisible()
  await expect(page.getByRole('contentinfo').getByText('Evidence map ready. Review the recommendation, then explicitly approve or skip it.')).toBeVisible()
  await page.getByRole('button', { name: /Show .* more sources/ }).click()
  const row = (name: string) => page.locator('.source-row').filter({ hasText: name })
  await row('Northstar Wire').getByRole('button', { name: 'Approve purchase S$0.20', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm purchase S$0.20', exact: true }).click()
  await page.getByRole('dialog', { name: 'Northstar Wire' }).getByLabel('Close evidence drawer').click()
  await row('Circuit Note').getByRole('button', { name: 'Skip S$0.30', exact: true }).click()
  const meridianBuy = row('Grid Operators Report').getByRole('button', { name: 'Approve purchase S$0.80', exact: true })
  if (await meridianBuy.count()) { await meridianBuy.click(); await page.getByRole('button', { name: 'Confirm purchase S$0.80', exact: true }).click(); await page.getByRole('dialog', { name: 'Grid Operators Report' }).getByLabel('Close evidence drawer').click() }
  await row('GridScope Asia').getByRole('button', { name: 'Block', exact: true }).click()
  await expect(page.getByText('GridScope blocked: S$1.40 exceeds the remaining S$1.00.').last()).toBeVisible()
  await page.getByRole('button', { name: 'Answer from available evidence' }).click()
  await expect(page.getByText('Dossier ready. Claims are linked to exact accessible spans.').last()).toBeVisible()
  await expect(page.getByText('FIXTURE RESEARCH · NOT INVESTMENT ADVICE')).toBeVisible()
  await expect(page.getByText('≈ S$1.00', { exact: false }).first()).toBeVisible()
})

