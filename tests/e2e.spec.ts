import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('S$2 story at stage pace, Show work, exact passage, PDF, then S$0 at real pace', async ({ page }) => {
  test.setTimeout(150_000)
  await page.goto('/')
  await expect(page.getByRole('textbox', { name: 'Your question' })).toHaveValue(/600 MW/)
  await page.getByRole('button', { name: /^Ask/ }).click()

  // Stage pace replays the recorded run, and says so.
  await expect(page.getByText('Stage pace · replaying the recorded run')).toBeVisible()
  await expect(page.getByRole('region', { name: 'Purchase: Grid Operators Report' })).toBeVisible({ timeout: 40_000 })
  await expect(page.getByRole('button', { name: 'Run finished' })).toBeVisible({ timeout: 60_000 })
  await expect(page.getByRole('status').filter({ hasText: 'Answer ready' })).toBeVisible()
  await expect(page).toHaveTitle('✓ Answer ready · ResearchAgent')
  await expect(page.getByLabel('Impact: QUALIFIES')).toBeVisible()
  await expect(page.getByRole('button', { name: /bought S\$0\.80/ })).toBeVisible()
  await expect(page.getByText('OVER CAP', { exact: true }).first()).toBeVisible()
  // The engine's own codes stay out of the surface and live in Show work.
  await expect(page.getByText('SKIP_OVER_CAP', { exact: true })).toHaveCount(0)
  await page.keyboard.press('w')
  const work = page.getByRole('dialog', { name: 'Show work' })
  await work.getByRole('tab', { name: 'Policy' }).click()
  await expect(work.getByText('SKIP_OVER_CAP', { exact: true }).first()).toBeVisible()
  await work.getByRole('tab', { name: 'Wire' }).click()
  await expect(work.getByRole('region', { name: 'HTTP exchange' }).getByText('sha-256 ✓', { exact: true }).first()).toBeVisible()
  await work.getByRole('button', { name: 'Close show work' }).click()

  await page.getByRole('button', { name: /Citation .*Grid Operators/ }).first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog').locator('mark')).toContainText(/240|14 months/)
  await page.getByRole('button', { name: 'Close source passage' }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download report ↓' }).click()
  const file = await (await download).path()
  expect(file).not.toBeNull()
  expect((await readFile(file!)).subarray(0, 5).toString()).toBe('%PDF-')
  const corpus = await page.request.get('/data/corpus/resources.json')
  expect(corpus.status()).toBe(403)
  expect(await corpus.text()).not.toContain('240 of the 600')

  // Presenter menu: real pace for the next question.
  await page.getByRole('button', { name: 'New question', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Your question' })).toBeVisible()
  await page.keyboard.press('.')
  await page.getByRole('dialog', { name: 'Presenter menu' }).getByRole('radio', { name: 'Real' }).click()
  await page.getByRole('button', { name: 'Close presenter menu' }).click()
  await page.getByRole('radio', { name: 'S$0', exact: true }).check()
  await page.getByRole('button', { name: /^Ask free/ }).click()
  await expect(page.getByRole('button', { name: 'Run finished' })).toBeVisible({ timeout: 20_000 })
  await expect(page.getByText('Stage pace · replaying the recorded run')).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Prompt budget' })).toContainText('Free-only run · no purchases authorized.')
  await expect(page.getByText(/^✓ ?bought S\$/)).toHaveCount(0)
  await expect(page.getByText('WOULD BUY', { exact: true }).first()).toBeVisible()
  await expect(page.getByText('BUY', { exact: true })).toHaveCount(0)
})
