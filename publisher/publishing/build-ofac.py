#!/usr/bin/env python3
"""Build-time only: authenticate the complete OFAC SDN XML before extracting XRP addresses."""
import argparse, hashlib, json, re, urllib.request, xml.etree.ElementTree as ET
ALPHABET="rpshnaf39wBUDNEGHJKLM4PQRST7VWXYZ2bcdeCg65jkm8oFqi1tuvAxyz"
def valid_address(value):
    if not value or not re.fullmatch(r"r[1-9A-HJ-NP-Za-km-z]{24,34}",value):return False
    number=0
    for char in value:number=number*58+ALPHABET.index(char)
    decoded=b"\0"*(len(value)-len(value.lstrip(ALPHABET[0])))+number.to_bytes((number.bit_length()+7)//8,"big")
    return len(decoded)==25 and decoded[0]==0 and hashlib.sha256(hashlib.sha256(decoded[:-4]).digest()).digest()[:4]==decoded[-4:]
from pathlib import Path
URL='https://sanctionslistservice.ofac.treas.gov/api/download/sdn.xml'
p=argparse.ArgumentParser(); p.add_argument('--sha256',required=True);p.add_argument('--file');p.add_argument('--output',default='publisher/publishing/ofac-xrp.json');args=p.parse_args()
if not re.fullmatch('[a-f0-9]{64}',args.sha256):p.error('Expected pinned lowercase SHA256')
if args.file:raw=Path(args.file).read_bytes()
else:
    with urllib.request.urlopen(URL,timeout=45) as response:raw=response.read(50*1024*1024+1)
if len(raw)>50*1024*1024 or hashlib.sha256(raw).hexdigest()!=args.sha256:raise SystemExit('OFAC source size or pinned hash mismatch')
if b'<!DOCTYPE' in raw or b'<!ENTITY' in raw:raise SystemExit('OFAC XML declarations forbidden')
root=ET.fromstring(raw); ns={'s':root.tag.split('}')[0][1:]}
if root.tag.split('}')[-1]!='sdnList':raise SystemExit('Expected SDN list')
addresses=[]
for entry in root.findall('s:sdnEntry',ns):
    for identity in entry.findall('s:idList/s:id',ns):
        if identity.findtext('s:idType',namespaces=ns)=='Digital Currency Address - XRP':
            address=identity.findtext('s:idNumber',namespaces=ns)
            if not valid_address(address):raise SystemExit('Malformed XRP address')
            addresses.append(address)
if not addresses:raise SystemExit('Expected at least one XRP address; review source/schema changes')
date=root.findtext('s:publshInformation/s:Publish_Date',namespaces=ns)
if not date:raise SystemExit('Missing SDN publication date')
snapshot={'source':URL,'sourceSha256':args.sha256,'listDate':date,'addresses':sorted(set(addresses))}
Path(args.output).parent.mkdir(parents=True,exist_ok=True);Path(args.output).write_text(json.dumps(snapshot,indent=2)+'\n')
# Desktop and other compiled engines stage TypeScript modules, not arbitrary JSON assets.
Path(args.output).with_suffix('.ts').write_text('// Generated by build-ofac.py from the authenticated JSON snapshot.\nexport default '+json.dumps(snapshot,indent=2)+' as const\n')
print(json.dumps({'addresses':len(snapshot['addresses']),'snapshotSha256':hashlib.sha256(json.dumps(snapshot,separators=(',',':')).encode()).hexdigest(),'sourceSha256':args.sha256}))
