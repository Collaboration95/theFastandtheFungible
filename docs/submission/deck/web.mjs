// Publish the finals deck as a browser slide deck: site/deck/index.html (served at /deck/ on Pages).
//   node docs/submission/deck/web.mjs     (export.mjs runs it after every successful PDF export)
// The page is a generated copy of docs/submission/deck/index.html: same slides, plus present.css/present.js
// (one slide at a time, keys, click, swipe, fullscreen, #n links). Edit the deck, never site/deck/.
// Assets: site files are linked in place, fonts come from site/brand/, everything else is copied to site/deck/assets/.
import { execFileSync } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '../../..')
const site = join(root, 'site')
const out = join(site, 'deck')
const assets = join(out, 'assets')

let html = readFileSync(join(here, 'index.html'), 'utf8')
rmSync(assets, { recursive: true, force: true })
mkdirSync(assets, { recursive: true })

const local = ref => !/^(?:[a-z]+:|#|\/\/)/i.test(ref)
function move(ref) {
  const abs = resolve(here, ref)
  if (!abs.startsWith(root)) throw new Error(`deck web: ${ref} is outside the repository`)
  if (abs.startsWith(site + '/')) return relative(out, abs)
  if (abs.includes('/node_modules/@fontsource-variable/')) {
    const font = join(site, 'brand', basename(abs))
    if (!existsSync(font)) throw new Error(`deck web: ${basename(abs)} is not in site/brand/`)
    return relative(out, font)
  }
  if (!existsSync(abs)) throw new Error(`deck web: missing ${ref}`)
  copyFileSync(abs, join(assets, basename(abs)))
  return `assets/${basename(abs)}`
}
html = html.replace(/(\bsrc=")([^"]+)(")/g, (m, a, ref, b) => local(ref) ? a + move(ref) + b : m)
html = html.replace(/(url\(['"]?)([^'")]+)(['"]?\))/g, (m, a, ref, b) => local(ref) ? a + move(ref) + b : m)
// Outside links open in a new tab, so the deck keeps its place.
html = html.replace(/<a href="(https?:\/\/[^"]+)"(?![^>]*target=)/g, '<a href="$1" target="_blank" rel="noopener"')
html = html.replace('</style>', `${readFileSync(join(here, 'present.css'), 'utf8')}</style>`)
html = html.replace(/<\/body>/i, `<script>\n${readFileSync(join(here, 'present.js'), 'utf8')}</script>\n</body>`)
html = html.replace('<head>', '<head>\n<!-- Generated by docs/submission/deck/web.mjs from docs/submission/deck/index.html. Do not edit. -->')
writeFileSync(join(out, 'index.html'), html)

// Shared site header and page metadata (OG card), as on every other site page.
for (const script of ['site-meta.mjs', 'site-header.mjs']) execFileSync(process.execPath, [join(root, 'scripts', script)], { cwd: root, stdio: 'inherit' })
console.log(`web deck → ${relative(root, out)}/index.html`)
